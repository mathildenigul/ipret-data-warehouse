-- =====================================================
-- IPRET - Bronze zone creation script
-- =====================================================

-- a. Database
CREATE OR REPLACE DATABASE ipret;

-- b. Schema
CREATE SCHEMA IF NOT EXISTS ipret.bronze;
USE SCHEMA ipret.bronze;

-- c. Tables (all raw columns as VARCHAR, loaded as-is from CSV)

-- Lookup tables
CREATE OR REPLACE TABLE TB_STATUT_EMPRUNTEUR (
    CD_STATUT_EMPRUNTEUR VARCHAR,
    LB_STATUT_EMPRUNTEUR VARCHAR
);

CREATE OR REPLACE TABLE TB_STATUT_PRET (
    CD_STATUT_PRET VARCHAR,
    LB_STATUT_PRET VARCHAR
);

CREATE OR REPLACE TABLE TB_TYPE_EMPRUNTEUR (
    CD_TYPE_EMPRUNTEUR VARCHAR,
    LB_TYPE_EMPRUNTEUR VARCHAR
);

CREATE OR REPLACE TABLE TB_TYPE_PRET (
    CD_TYPE_PRET VARCHAR,
    LB_TYPE_PRET VARCHAR
);

CREATE OR REPLACE TABLE TB_MODE_REMBOURSEMENT (
    CD_MODE_REMBOURSEMENT VARCHAR,
    LB_MODE_REMBOURSEMENT VARCHAR
);

CREATE OR REPLACE TABLE TB_PERIODICITE_REMBOURSEMENT (
    CD_PERIODICITE_REMBOURSEMENT VARCHAR,
    LB_PERIODICITE_REMBOURSEMENT VARCHAR
);

-- Main tables
CREATE OR REPLACE TABLE TB_EMPRUNTEUR (
    ID_EMPRUNTEUR           VARCHAR,
    LB_CIVILITE_EMPRUNTEUR  VARCHAR,
    LB_NOM_EMPRUNTEUR       VARCHAR,
    LB_PRENOM_EMPRUNTEUR    VARCHAR,
    DT_NAISSANCE_EMPRUNTEUR VARCHAR,
    LB_EMAIL_EMPRUNTEUR     VARCHAR,
    CD_POSTAL_EMPRUNTEUR    VARCHAR,
    CD_TYPE_EMPRUNTEUR      VARCHAR,
    CD_STATUT_EMPRUNTEUR    VARCHAR
);

CREATE OR REPLACE TABLE TB_PRET (
    ID_PRET                      VARCHAR,
    DT_PRET                      VARCHAR,
    MT_PRET                      VARCHAR,
    NB_DUREE_REMBOURSEMENT       VARCHAR,
    TX_INTERET_PRET              VARCHAR,
    CD_TYPE_PRET                 VARCHAR,
    ID_EMPRUNTEUR                VARCHAR,
    CD_STATUT_PRET               VARCHAR,
    CD_PERIODICITE_REMBOURSEMENT VARCHAR
);

CREATE OR REPLACE TABLE TB_REMBOURSEMENT (
    ID_REMBOURSEMENT      VARCHAR,
    DT_REMBOURSEMENT      VARCHAR,
    MT_REMBOURSE          VARCHAR,
    MT_CAPITAL_PAYE       VARCHAR,
    MT_INTERET_PAYE       VARCHAR,
    CD_MODE_REMBOURSEMENT VARCHAR,
    ID_PRET               VARCHAR
);

